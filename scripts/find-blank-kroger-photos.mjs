/**
 * Kroger answers a missing product photo with HTTP 200 and a blank ~300-byte
 * PNG instead of a 404, so a browser can't tell it from a real photo (the
 * response has no CORS headers, so pixels can't be read either). This scans
 * every active catalog product's Kroger ID and writes the ones with a blank
 * photo to apps/marketplace/src/lib/blank-photos.ts; the Marketplace then
 * shows its category mark instead of an empty frame.
 *
 * Re-run when the catalog changes:  node scripts/find-blank-kroger-photos.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const products = JSON.parse(await readFile(new URL('packages/catalog/products.json', root), 'utf8'));
const ids = [
  ...new Set(
    products.flatMap((product) =>
      product.identities.filter((identity) => identity.retailer === 'kroger').map((i) => i.productId),
    ),
  ),
].sort();

/** A real photo is a multi-KB JPEG; the placeholder is a PNG under 1 KB. */
async function isBlank(id) {
  for (const resolution of ['medium', 'large']) {
    const response = await fetch(`https://www.kroger.com/product/images/${resolution}/front/${id}`);
    const bytes = (await response.arrayBuffer()).byteLength;
    if (!response.ok || bytes < 1500 || response.headers.get('content-type')?.includes('png')) return true;
  }
  return false;
}

const blank = [];
for (let i = 0; i < ids.length; i += 8) {
  const batch = ids.slice(i, i + 8);
  const results = await Promise.all(batch.map((id) => isBlank(id).catch(() => false)));
  batch.forEach((id, index) => results[index] && blank.push(id));
}

const out = fileURLToPath(new URL('apps/marketplace/src/lib/blank-photos.ts', root));
await writeFile(
  out,
  `/**
 * Kroger product IDs whose photo is Kroger's blank placeholder. Generated by
 * scripts/find-blank-kroger-photos.mjs; do not edit by hand.
 */
export const BLANK_KROGER_PHOTOS: ReadonlySet<string> = new Set([
${blank.map((id) => `  '${id}',`).join('\n')}
]);
`,
);
console.log(`${blank.length} of ${ids.length} Kroger products have a blank photo:`, blank.join(' '));
